pub(super) fn resolve(name: &CStr) -> Option<c_int> {
  // This CEF API is declared in cef_id_mappers.h but is missing from cef-rs bindings.
  let id = unsafe { cef_id_for_command_id_name(name.as_ptr()) };
  (id != -1).then_some(id)
}
